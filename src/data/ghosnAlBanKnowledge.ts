export interface GroundedSearchResult {
  matchedSections: BookSection[];
  synthesizedAnswer: string;
}

export function searchGhosnAlBan(
  query: string,
  extraSections: BookSection[] = []
): GroundedSearchResult {
  const allSections = [...extraSections, ...BOOK_SECTIONS];
  const normQuery = normalizeArabic(query);
  const tokens = normQuery
    .split(' ')
    .filter((t) => t.length >= 2 && !STOP_WORDS.has(t));

  const scored = allSections.map((section) => {
    let score = 0;
    const normTitle = normalizeArabic(section.chapterTitle);
    const normSummary = normalizeArabic(section.summary);
    const normQuote = normalizeArabic(section.verbatimQuote);
    const normDetails = normalizeArabic(section.details.join(' '));
    const normKeywords = section.keywords.map(normalizeArabic);

    // Exact phrase match bonus
    if (normQuery.length > 3) {
      if (normTitle.includes(normQuery)) score += 35;
      if (normKeywords.some((k) => normQuery.includes(k) || k.includes(normQuery))) score += 30;
      if (normSummary.includes(normQuery)) score += 20;
      if (normQuote.includes(normQuery)) score += 18;
      if (normDetails.includes(normQuery)) score += 15;
    }

    for (const token of tokens) {
      if (normTitle.includes(token)) score += 12;
      if (normKeywords.some((k) => k.includes(token) || token.includes(k))) score += 14;
      if (normSummary.includes(token)) score += 8;
      if (normQuote.includes(token)) score += 7;
      if (normDetails.includes(token)) score += 6;
    }

    return { section, score };
  });

  scored.sort((a, b) => b.score - a.score);

  const topMatches = scored
    .filter((item) => item.score > 0)
    .slice(0, 3)
    .map((item) => item.section);

  const finalSections = topMatches.length > 0 ? topMatches : [BOOK_SECTIONS[2], BOOK_SECTIONS[3]];

  const primary = finalSections[0];
  let answer = `بحسب ما ورد في مرجع **«${GHOSN_AL_BAN_META.title}»** للشيخ إبراهيم بن صالح باباحمو أعزام (${primary.pages}):\n\n`;
  answer += `${primary.summary}\n\n`;
  answer += `**أبرز التفاصيل الموثّقة في هذا الباب:**\n`;
  for (const detail of primary.details) {
    answer += `• ${detail}\n`;
  }

  if (finalSections.length > 1) {
    const secondary = finalSections[1];
    answer += `\nكما يرتبط بسؤالك ما جاء في فصل **«${secondary.chapterTitle}»** (${secondary.pages}):\n${secondary.summary}`;
  }

  return {
    matchedSections: finalSections,
    synthesizedAnswer: answer
  };
}
