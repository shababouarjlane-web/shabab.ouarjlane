async def generate_all():
    output_dir = os.path.join(os.getcwd(), "public", "audio", "tour")
    os.makedirs(output_dir, exist_ok=True)
    voice = "ar-DZ-IsmaelNeural" # صوت وثائقي جزائري طبيعي جداً وفصيح
    rate = "-3%" # وتيرة إلقاء هادئة ووقورة كالأفلام الوثائقية

    print(f"Generating studio-quality audio with voice: {voice}")
    for item in STOPS_DATA:
        dest_file = os.path.join(output_dir, item["filename"])
        print(f"Generating: {item['filename']}...")
        communicate = edge_tts.Communicate(item["text"], voice, rate=rate)
        await communicate.save(dest_file)
        size_kb = os.path.getsize(dest_file) / 1024
        print(f" -> Done: {item['filename']} ({size_kb:.1f} KB)")

    print("All audio files generated successfully!")

if __name__ == "__main__":
    asyncio.run(generate_all())
