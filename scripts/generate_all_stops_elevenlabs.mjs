async function runAll() {
  const outputDir = path.resolve(process.cwd(), 'public', 'audio', 'tour');

  for (const stop of ALL_STOPS) {
    const dest = path.join(outputDir, stop.filename);
    console.log(`Generating ElevenLabs George for: ${stop.filename}...`);

    const audioStream = await client.textToSpeech.convert('JBFqnCBsd6RMkjVDRZzb', {
      text: stop.text,
      modelId: 'eleven_multilingual_v2',
      voiceSettings: {
        stability: 0.55,
        similarityBoost: 0.85
      }
    });

    const stream = Readable.fromWeb(audioStream);
    const writeStream = createWriteStream(dest);
    await new Promise((resolve, reject) => {
      stream.pipe(writeStream).on('finish', resolve).on('error', reject);
    });
    console.log(` -> Completed: ${stop.filename}`);
  }

  console.log('ALL 6 STOPS GENERATED SUCCESSFULLY VIA ELEVENLABS GEORGE!');
}

runAll().catch(console.error);
